export function normalizeLocale(locale) {
  return locale === 'en' ? 'en' : 'zh'
}

export function getLocale() {
  const stored = uni.getStorageSync(LOCALE_KEY)
  return normalizeLocale(stored)
}

export function setLocale(locale) {
  const normalized = normalizeLocale(locale)
  uni.setStorageSync(LOCALE_KEY, normalized)
  return normalized
}

export function getCopy(scope, locale = getLocale()) {
  const normalized = normalizeLocale(locale)
  return (messages[normalized] && messages[normalized][scope]) || {}
}

export function formatMessage(template, params = {}) {
  return String(template || '').replace(/\{(\w+)\}/g, (_, key) => {
    const value = params[key]
    return value === undefined || value === null ? '' : String(value)
  })
}

export function applyTabBarLocale(locale = getLocale()) {
  const tabBar = getCopy('tabBar', locale)
  try {
    tabBar.forEach((text, index) => {
      uni.setTabBarItem({ index, text })
    })
  } catch (err) {
    // Non-tab pages or early app boot can throw here.
  }
}

export function applyPageLocale(pageKey, locale = getLocale()) {
  const navTitles = getCopy('navTitles', locale)
  const title = navTitles[pageKey]
  if (title) {
    try {
      uni.setNavigationBarTitle({ title })
    } catch (err) {
      // Ignore title failures on unsupported runtimes.
    }
  }
  applyTabBarLocale(locale)
}
